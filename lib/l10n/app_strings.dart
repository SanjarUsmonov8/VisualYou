import 'package:flutter/material.dart';

class AppStrings {
  const AppStrings(this.locale);

  final Locale locale;

  static const supportedLocales = [
    Locale('en'),
    Locale('es'),
    Locale('ru'),
    Locale('fr'),
    Locale('uz'),
  ];

  static AppStrings of(BuildContext context) {
    return Localizations.of<AppStrings>(context, AppStrings) ??
        AppStrings(Localizations.localeOf(context));
  }

  String text(String key) {
    return _translations[locale.languageCode]?[key] ??
        _translations['en']![key] ??
        key;
  }

  String added(String habit) {
    return switch (locale.languageCode) {
      'es' => 'Se añadió $habit',
      'ru' => 'Добавлено: $habit',
      'fr' => '$habit ajouté',
      'uz' => '$habit qo‘shildi',
      _ => '$habit added',
    };
  }

  static const delegate = _AppStringsDelegate();
}

class _AppStringsDelegate extends LocalizationsDelegate<AppStrings> {
  const _AppStringsDelegate();

  @override
  bool isSupported(Locale locale) {
    return AppStrings.supportedLocales.any(
      (supported) => supported.languageCode == locale.languageCode,
    );
  }

  @override
  Future<AppStrings> load(Locale locale) async => AppStrings(locale);

  @override
  bool shouldReload(_AppStringsDelegate old) => false;
}

extension AppStringsContext on BuildContext {
  String tr(String key) => AppStrings.of(this).text(key);

  String habitAdded(String habit) => AppStrings.of(this).added(habit);
}

